import type { OnboardingStepBrief } from '@/server/onboarding/service';

/**
 * Консультант и незаконченный онбординг (решение владельца 09.10):
 *  - свободный вопрос посреди шага (ход с `onboarding`) — коротко ответить и вернуть к шагу;
 *  - онбординг брошен («Настроить позже») — в разговоре напомнить и дать ссылку на продолжение.
 * Тексты контекста хода — здесь, правило поведения — в prompts/consultant.md (<onboarding>).
 */

/** Куда вести продолжать: /onboarding открывается на сохранённом шаге. */
export const ONBOARDING_RESUME_PATH = '/onboarding';

const optionsLine = (s: OnboardingStepBrief) => (s.options.length ? ` Варианты: ${s.options.join('; ')}.` : '');

/** Контекст хода: человек задал свободный вопрос посреди шага онбординга. */
export function asideNote(step: OnboardingStepBrief): string {
  return [
    'Идёт онбординг: анкета не закончена, человек сейчас на шаге «' + step.question + '».' + (step.sub ? ` Пояснение шага: ${step.sub}` : '') + optionsLine(step),
    'Он написал не ответ на шаг, а свой вопрос или реплику. Ответь коротко (1–3 предложения) по существу и одной фразой мягко верни к шагу — кнопки шага интерфейс покажет сам под твоим ответом.',
    'Не отвечай на шаг за человека и не перечисляй варианты заново. Инструменты вызывай, только если без данных платформы не ответить; ask_user не вызывай.',
    'Как устроена платформа (кто что видит, уведомления, сроки), говори только то, что знаешь из этих инструкций или инструментов; не знаешь — так и скажи, не додумывай.',
  ].join('\n');
}

/** Контекст хода: онбординг брошен — напомнить один раз за разговор. */
export function resumeNote(step: OnboardingStepBrief): string {
  return `Онбординг кандидата не закончен (остановился на шаге «${step.question}»). Если в этом разговоре ты ещё не напоминал об этом — в конце ответа одной фразой предложи продолжить знакомство со ссылкой ${ONBOARDING_RESUME_PATH} (откроется с того же шага). Уже напоминал — не повторяй.`;
}

/** Ответ без модели (заглушка LLM, демо-режим, сбой): честно и с возвратом к шагу. */
export function asideCannedReply(step: OnboardingStepBrief): string {
  return `Сейчас я отвечаю без языковой модели, поэтому на свободные вопросы отвечу подробнее после знакомства — в этом же чате. Вернёмся к вопросу «${step.question}».`;
}

/** Строка-напоминание для ответов без модели (демо, план В). */
export function resumeLine(): string {
  return `Знакомство ещё не закончено — продолжить можно здесь: ${ONBOARDING_RESUME_PATH}.`;
}
