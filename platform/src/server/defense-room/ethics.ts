/**
 * Вопросы работодателя, не связанные с работой (защищённые признаки: ст. 3 и 64 ТК РФ — возраст,
 * семейное положение и дети, национальность и происхождение, религия, здоровье, политические
 * взгляды, ориентация). Детерминированная проверка без модели: вопрос из очереди с такой темой
 * не принимается (ИИ не должен зачитывать его вслух), живая реплика с такой темой не блокируется
 * (это речь человека), но Кира сразу делает ремарку, а ответ кандидата на неё не уходит оценщику.
 *
 * Шаблоны требуют личного контекста («у вас есть дети», «сколько вам лет»), чтобы технические
 * вопросы («возраст записи в кэше», «дочерние узлы», «здоровье сервиса») не срабатывали.
 * Это эвристика: перефразированный вопрос она пропустит — работодатель за свои слова отвечает сам.
 */

export type SensitiveTopic = 'age' | 'family' | 'origin' | 'religion' | 'health' | 'politics' | 'orientation';

const NB = '(?<![а-яёa-z])';
