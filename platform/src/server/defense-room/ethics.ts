export const TOPIC_LABEL: Record<SensitiveTopic, string> = {
  age: 'возраст',
  family: 'семья и дети',
  origin: 'национальность и происхождение',
  religion: 'религия',
  health: 'здоровье',
  politics: 'политические взгляды',
  orientation: 'личная жизнь',
};

/** Защищённые темы в тексте работодателя; пустой массив — вопрос по делу. */
export function sensitiveTopics(text: string): SensitiveTopic[] {
  const t = text.replace(/ё/gi, (m) => (m === 'Ё' ? 'Е' : 'е')).replace(/\s+/g, ' ');
  // ё и е в шаблонах: нормализуем текст к «е», шаблоны с «ё» проверяем на исходном тексте тоже.
  return RULES.filter((r) => r.re.test(t) || r.re.test(text)).map((r) => r.topic);
}

const topicsText = (topics: SensitiveTopic[]) => topics.map((t) => TOPIC_LABEL[t]).join(', ');

/** Отказ в постановке вопроса в очередь (его зачитывала бы Кира). */
export function rejectMessage(topics: SensitiveTopic[]): string {
  return `Вопрос касается темы «${topicsText(topics)}» - это не связано с работой, и задавать его кандидату нельзя (ст. 3 и 64 ТК РФ). Спросите о навыках, проекте или условиях работы.`;
}

/** Ремарка Киры после живой реплики работодателя на защищённую тему: кандидату и работодателю. */
export function ethicsNotice(topics: SensitiveTopic[]): string {
  return `Небольшая ремарка: вопрос про ${topicsText(topics)} не связан с работой. Отвечать на него не обязательно, на оценку защиты это не влияет.`;
}
