/**
 * ПРЕДЛОЖЕНИЕ: множитель покрытия за категорию из теста (R-M-01, R-M-02). Категория
 * совпала со специализацией потребности: грейд равен — покрытие × 1,3; выше
 * требуемого — × 1,2; ниже — × 1. Множитель, а не прибавка: категория без
 * закрытых требований не поднимает кандидата над тем, кто их закрыл (первый
 * прогон eval с прибавкой +0,15/+0,10 это показал — docs/validation-results.md).
 * Контракт с лейном test: читаем последнюю CandidateCategory как есть.
 */
export const CATEGORY_MULT_EXACT = 0.3;
export const CATEGORY_MULT_ABOVE = 0.2;
/**
 * ПРЕДЛОЖЕНИЕ (Q-36, решение владельца 10.10; R-M-01 «выдача по категориям из опроса+теста, не по
 * самоописанию»): базовая величина совпавшей категории. Балл кандидата с категорией, совпавшей со
 * специализацией потребности (грейд равен или выше), = (покрытие + CATEGORY_BASE) × (1 + множитель).
 * Порядок, который это даёт: при одном покрытии «категория + закрытое» > «только категория»
 * (покрытие > 0) и > «только утверждения» (выигрыш CATEGORY_BASE × (1 + множитель) ≈ 0,065).
 * «Только категория» (0,065 / 0,06) стоит над кандидатом без категории, закрывшим одно требование
 * слабо (покрытие до ~0,06), и под всеми, кто закрыл заметную долю. Строго «только категория» над
 * любым «только утверждения» невозможно без нарушения принципа выше: 0,10 в первом прогоне
 * подняло кандидата с категорией и 2 из 6 над кандидатом без категории с 6 из 6 (eval, fe-j-2).
 * Калибровка — eval/matching.
 */
export const CATEGORY_BASE = 0.05;
/** ПРЕДЛОЖЕНИЕ: специализация кандидата (категория, иначе указанная) не совпала с потребностью. */
export const SPEC_MISMATCH_PENALTY = 0.2;
/** ПРЕДЛОЖЕНИЕ (R-M-02): есть подтверждённые достижения ФСП (fspState = linked). Отсутствие ФСП не штрафуется (R-FSP-03). */
export const FSP_BOOST = 0.05;
/**
 * ПРЕДЛОЖЕНИЕ (R-M-02 «внутри категории: результаты теста + достижения ФСП»): вес достижений, когда их
 * список известен (fsp-weight.ts). Очки достижения = место × уровень соревнования × затухание по давности;
 * прибавка = FSP_PER_POINT × Σ очков, не больше FSP_BOOST_MAX. Потолок 0,06 ниже вклада требования весом 2
 * из 10, закрытого артефактом (0,10): ФСП уточняет порядок среди близких по покрытию, но не поднимает над
 * тем, кто доказанно закрыл больше. Требование «со слов» (0,05 при том же весе) потолок перекрыть может —
 * это осознанно: третья сторона (ФСП) сильнее самоописания. Без ФСП — 0, не штраф (R-FSP-03).
 * Список не загружен (старые данные, eval) — прежняя плоская прибавка FSP_BOOST.
 */
export const FSP_PER_POINT = 0.05;
export const FSP_BOOST_MAX = 0.06;
/** Затухание: вес достижения падает вдвое каждые FSP_HALF_LIFE_YEARS лет. */
export const FSP_HALF_LIFE_YEARS = 2;
/** ПРЕДЛОЖЕНИЕ: место (победа 1; призовое 0,7; финал 0,4; участие 0,15). Модель достижений — наша (CLAUDE.md п. 4). */
