import { splitSentences, stableSentences } from '@/lib/sentences';

describe('нарезка реплики: русские сокращения, числа, знаки конца (лейн call-speed)', () => {
  it('«т.е.», «т.к.», «напр.», «т. е.» — не конец предложения', () => {
    expect(splitSentences('Индекс ускоряет чтение, т.е. запросы по ключу. Но запись становится дороже, т.к. дерево надо обновлять.')).toEqual([
      'Индекс ускоряет чтение, т.е. запросы по ключу.',
      'Но запись становится дороже, т.к. дерево надо обновлять.',
    ]);
    expect(splitSentences('Возьми простой пример, напр. Таблицу заказов. Что в ней будет первичным ключом?')).toEqual([
      'Возьми простой пример, напр. Таблицу заказов.',
      'Что в ней будет первичным ключом?',
    ]);
    expect(splitSentences('Это кэш, т. е. копия данных рядом с приложением. Когда её надо сбрасывать?')).toEqual([
      'Это кэш, т. е. копия данных рядом с приложением.',
      'Когда её надо сбрасывать?',
    ]);
  });

  it('«и т.д.» в середине (дальше строчная) — склейка; в конце фразы — граница', () => {
    expect(splitSentences('Логи, метрики, трейсы и т.д. и всё это в одном месте. Как ты это настраивал?')).toEqual([
      'Логи, метрики, трейсы и т.д. и всё это в одном месте.',
      'Как ты это настраивал?',
    ]);
    expect(splitSentences('Бывают логи, метрики, трейсы и т.д. Что из этого ты настраивал сам?')).toEqual([
      'Бывают логи, метрики, трейсы и т.д.',
      'Что из этого ты настраивал сам?',
    ]);
  });

  it('числа «1.5» и версии не режутся; вопрос и восклицание — границы', () => {
    expect(splitSentences('Запрос шёл 1.5 секунды на версии 2.3.1 базы. Отлично, это хороший результат! Что ты сделал дальше?')).toEqual([
      'Запрос шёл 1.5 секунды на версии 2.3.1 базы.',
      'Отлично, это хороший результат!',
      'Что ты сделал дальше?',
    ]);
  });
});

describe('потоковая нарезка stableSentences: отданное не меняется, сколько бы текста ни пришло', () => {
  const texts = [
    'Хорошо, понял тебя. Давай перейдём к схеме данных. Как бы ты хранил историю цен товара, т.е. что меняется во времени?',
    'Отлично! Ок. Расскажи про индексы: когда составной индекс лучше двух отдельных? И т.д. и т.п. мелочи не важны.',
    'Привет! Начнём со знакомства. Да?',
    'Запрос шёл 1.5 секунды. Как ускорить? Ок.',
    `${'длинное слово '.repeat(30)}и в конце вопрос?`,
  ];

  for (const text of texts) {
    it(`каждый префикс даёт префикс итогового разбиения: «${text.slice(0, 30)}…»`, () => {
      const full = splitSentences(text);
      let prev: string[] = [];
      for (let i = 0; i <= text.length; i++) {
        const got = stableSentences(text.slice(0, i));
        expect(got, `префикс ${i}`).toEqual(full.slice(0, got.length));
        expect(got.length, `не уменьшается на ${i}`).toBeGreaterThanOrEqual(prev.length);
        prev = got;
      }
    });
  }

  it('первое предложение отдаётся, как только за ним пошёл достаточно длинный хвост', () => {
    expect(stableSentences('Хорошо, понял тебя.')).toEqual([]);
    expect(stableSentences('Хорошо, понял тебя. Да')).toEqual([]);
    expect(stableSentences('Хорошо, понял тебя. Давай дальше пойдём')).toEqual(['Хорошо, понял тебя.']);
  });
});
